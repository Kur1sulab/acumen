class TestTriStateLiveServer(unittest.TestCase):
    """起真 server，用真响应判三态：这是「不能只测命中」的那一半。"""

    @classmethod
    def setUpClass(cls):
        cls.srv = ThreadingHTTPServer(("127.0.0.1", 0), _Handler)
        cls.base = f"http://127.0.0.1:{cls.srv.server_address[1]}"
        cls.th = threading.Thread(target=cls.srv.serve_forever, daemon=True)
        cls.th.start()

    @classmethod
    def tearDownClass(cls):
        cls.srv.shutdown()
        cls.srv.server_close()

    def _classify(self, path):
        status, headers, body = fetch(self.base + path)
        return waf.classify(status=status, headers=headers, body=body)

    def test_plain_404_is_absent(self):
        v = self._classify("/plain404")
        self.assertEqual(v["state"], waf.ABSENT, v["reason"])
        self.assertTrue(waf.absent_is_confirmed(v))

    def test_cloudflare_403_is_blocked(self):
        v = self._classify("/cloudflare403")
        self.assertEqual(v["state"], waf.BLOCKED, v["reason"])
        self.assertEqual(v["waf"], "Cloudflare")
        self.assertFalse(waf.absent_is_confirmed(v))

    def test_404_with_block_page_is_blocked_not_absent(self):
        """国产 WAF 常用 404 伪装拦截页：状态码说「没有」，正文说「被拦」。"""
        v = self._classify("/safedog404")
        self.assertEqual(v["state"], waf.BLOCKED, v["reason"])
        # Cookie 里同时可能带别家 CDN 的标记，这里只要求「认得出是谁拦的」
        self.assertIn("安全狗", v["waf_names"])

    def test_502_is_unknown(self):
        v = self._classify("/err502")
        self.assertEqual(v["state"], waf.UNKNOWN, v["reason"])

    def test_challenge_page_is_unknown(self):
        v = self._classify("/challenge")
        self.assertEqual(v["state"], waf.UNKNOWN, v["reason"])

    def test_modsecurity_406_is_blocked(self):
        v = self._classify("/modsec406")
        self.assertEqual(v["state"], waf.BLOCKED, v["reason"])
        self.assertEqual(v["waf"], "ModSecurity")

    def test_healthy_200_is_present(self):
        v = self._classify("/ok")
        self.assertEqual(v["state"], waf.PRESENT, v["reason"])


