FAKE_ENGINE = r"""#!/bin/sh
# 假 sweep：按 WAF_MODE 写一份形态不同的 paths.json，用来验证 scan 结果里的三态。
if [ $# -eq 0 ]; then echo "sweep — fake engine for tests (0.0.1)"; exit 0; fi
PROG=""; TARGET=""
prev=""
for a in "$@"; do
  if [ "$prev" = "--progress-file" ]; then PROG="$a"; fi
  if [ "$prev" = "-t" ] || [ "$prev" = "-u" ] || [ "$prev" = "-d" ]; then TARGET="$a"; fi
  prev="$a"
done
ev() { printf '{"ts": 1.5, "event": "%s", "module": "%s", "detail": "%s"}\n' "$1" "$2" "$3" >> "$PROG"; }
ev pipeline_start pipeline "$TARGET"
ev start paths ""
mkdir -p "out/$TARGET"
case "${WAF_MODE:-blocked}" in
  blocked)
    printf '{"base":"%s","server":"cloudflare","alive":[],"notes":[{"path":"/.git/config","status":403,"verdict":"被拒绝（可能受保护/WAF）"}],"baseline":{"kind":"uniform403","status":403,"digest":"x","size":40,"ctype":"text/html","final_url":"%s/_probe","samples":2}}\n' "$TARGET" "$TARGET" > "out/$TARGET/paths.json" ;;
  absent)
    printf '{"base":"%s","alive":[],"notes":[],"baseline":{"kind":"normal","status":404,"digest":"x","size":40,"ctype":"text/html","final_url":"%s/_probe","samples":2}}\n' "$TARGET" "$TARGET" > "out/$TARGET/paths.json" ;;
  unknown)
    printf '{"base":"%s","alive":[],"notes":[],"baseline":{"kind":"unknown","samples":1}}\n' "$TARGET" > "out/$TARGET/paths.json" ;;
esac
ev done paths ""
ev pipeline_end pipeline done
exit 0
"""


def make_engine(dirpath):
    p = os.path.join(dirpath, "sweep")
    with open(p, "w", encoding="utf-8") as f:
        f.write(FAKE_ENGINE)
    os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR)
    return p


def wait_for(fn, timeout=15.0, step=0.1):
    end = time.time() + timeout
    while time.time() < end:
        v = fn()
        if v:
            return v
        time.sleep(step)
    return fn()


class TestScanWiring(unittest.TestCase):
    """三态必须进 scan 的结果结构，不是只进日志。"""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="vc-waf-scan-")
        self.inbox = os.path.join(self.tmp, "inbox")
        os.makedirs(self.inbox)
        self.db = os.path.join(self.tmp, "vuln.db")
        self.engine = make_engine(self.tmp)
        self.store = Store(self.db)
        self.mgr = ScanManager(self.db, self.inbox, engine=self.engine, timeout=60,
                               max_parallel=1, ingest_cb=Ingestor(self.store, [self.inbox]).scan)

    def tearDown(self):
        self.mgr.shutdown()
        shutil.rmtree(self.tmp, ignore_errors=True)

    def _run(self, mode_env):
        os.environ["WAF_MODE"] = mode_env
        try:
            res = self.mgr.start("paths", ["127.0.0.1:8899"], parallel=1)
            job_id = res["job_id"]

            def done():
                j = self.mgr.job(job_id)
                return j if j and j["status"] in ("ok", "failed", "partial", "stopped") else None

            job = wait_for(done)
            self.assertIsNotNone(job, "任务没在超时内结束")
            return job_id, job
        finally:
            os.environ.pop("WAF_MODE", None)

    def test_blocked_run_is_marked_blocked(self):
        _, job = self._run("blocked")
        run = job["runs"][0]
        self.assertEqual(run["waf"]["state"], "blocked", run["waf"])
        self.assertEqual(run["waf"]["waf"], "Cloudflare")
        self.assertEqual(run["findings"], 0)
        self.assertEqual(job["counts"]["waf_blocked"], 1)
        # 落库了：换一次读库也能拿到（不是只在内存里）
        row = self.mgr._rows("SELECT waf_state, waf FROM scan_runs WHERE job_id=?", (job["id"],))[0]
        self.assertEqual(row["waf_state"], "blocked")
        self.assertEqual(row["waf"], "Cloudflare")
        # 日志必须说清「0 命中不代表不存在」
        joined = "\n".join(job["log"]["lines"])
        self.assertIn("[WAF]", joined)
        self.assertIn("不代表", joined)

    def test_absent_run_is_marked_absent(self):
        _, job = self._run("absent")
        self.assertEqual(job["runs"][0]["waf"]["state"], "absent")
        self.assertEqual(job["counts"]["waf_blocked"], 0)

    def test_unknown_run_is_marked_unknown(self):
        _, job = self._run("unknown")
        self.assertEqual(job["runs"][0]["waf"]["state"], "unknown")

    def test_ingest_marks_findings_and_keeps_note(self):
        """产物说明里必须写明「被拦」，否则报告上的「没有存活路径」还是会被读成「都没有」。"""
        job_id, job = self._run("blocked")
        self.assertIsNotNone(job)
        job = job or {}
        deadline = time.time() + 6
        while time.time() < deadline and self.store.summary()["files"] < 1:
            time.sleep(0.1)
        self.assertGreaterEqual(self.store.summary()["files"], 1, "产物没被摄入")
        # 0 命中也要留下说明：文件表里有记录，且结论不是「确认存在 0 条」
        self.assertEqual(self.store.findings()["total"], 0)
        # 解析层的说明文字必须点明「被拦」而不是「没有」
        art = os.path.join(job["dir"], "out", "https://127.0.0.1:8899", "paths.json")
        self.assertTrue(os.path.isfile(art), art)
        with open(art, encoding="utf-8") as fh:
            res = pss.parse(fh.read(), art)
        assert res is not None
        self.assertIn("被 WAF 拦", res.note)
        self.assertIn("不代表这些路径不存在", res.note)


class TestParseStamping(unittest.TestCase):
    """三态要跟着产物贴到命中上：命中的那一行也得能看出这轮到底是啥情形。"""

    @staticmethod
    def _parse(doc, name="a.example/paths.json"):
        res = pss.parse(json.dumps(doc), "/tmp/" + name)
        assert res is not None, "paths.json 没被认出来"
        return res

    def test_blocked_paths_note(self):
        doc = {"base": "http://a.example", "alive": [], "notes": [],
               "baseline": {"kind": "uniform403", "status": 403, "samples": 2}}
        res = self._parse(doc)
        self.assertEqual(res.findings, [])
        self.assertIn("被 WAF 拦", res.note)
        self.assertIn("不代表这些路径不存在", res.note)

    def test_absent_paths_note_has_no_waf_warning(self):
        doc = {"base": "http://a.example", "alive": [], "notes": [],
               "baseline": {"kind": "normal", "status": 404, "samples": 2}}
        res = self._parse(doc)
        self.assertIn("没有存活路径", res.note)
        self.assertNotIn("被 WAF 拦", res.note)

    def test_findings_from_soft404_doc_are_unknown(self):
        """软 404 站点上的「命中」本身就是可疑的：标不确定，别当铁证也别当没有。"""
        doc = {"base": "http://a.example",
               "baseline": {"kind": "soft404", "status": 200, "samples": 2},
               "alive": [{"path": "/.env", "status": 200, "size": 30,
                          "final_url": "http://a.example/.env", "verified": True}],
               "notes": []}
        res = self._parse(doc)
        self.assertTrue(res.findings)
        self.assertEqual(res.findings[0]["waf_state"], "unknown")

    def test_store_keeps_stamped_state(self):
        tmp = tempfile.mkdtemp(prefix="vc-waf-stamp-")
        try:
            doc = {"base": "http://a.example",
                   "baseline": {"kind": "uniform403", "status": 403, "samples": 2},
                   "alive": [], "notes": []}
            text = json.dumps(doc)
            s = Store(os.path.join(tmp, "v.db"))
            # 直接塞一条带状态的命中，验证入库不被丢掉
            s.add_findings([{"title": "路径可访问：/.env", "sev": "high", "asset": "a.example",
                             "endpoint": "http://a.example/.env", "source": "sweep-paths",
                             "waf_state": waf.BLOCKED, "waf": "Cloudflare"}], "paths.json")
            self.assertEqual(s.findings(waf="blocked")["total"], 1)
            self.assertEqual(s.findings(waf="absent")["total"], 0)
            self.assertTrue(text)
        finally:
            shutil.rmtree(tmp, ignore_errors=True)


# ---------------------------------------------------------------- 复验链路

VERIFY_ENGINE = r"""#!/bin/sh
# 假 sweep（复验用）：按 WAF_VERIFY_MODE 写出「正常没了」或「被拦了」两种产物。
HOST=$(echo "$*" | sed -n 's/.*-u \(http[s]*:\/\/[^ ]*\).*/\1/p' | sed 's#.*//##')
DIR="out/$(echo "$HOST" | sed 's/[:.]/_/g')"
mkdir -p "$DIR"
case "${WAF_VERIFY_MODE:-gone}" in
  blocked)
    printf '{"base":"http://%s","server":"cloudflare","alive":[],"notes":[{"path":"/.env","status":403,"verdict":"被拒绝（可能受保护/WAF）"}],"baseline":{"kind":"uniform403","status":403,"digest":"x","size":40,"samples":2}}\n' "$HOST" > "$DIR/paths.json" ;;
  gone)
    printf '{"base":"http://%s","alive":[],"baseline":{"kind":"normal","status":404,"digest":"x","size":40,"samples":2}}\n' "$HOST" > "$DIR/paths.json" ;;
esac
exit 0
"""


class TestVerifyWiring(unittest.TestCase):
    """复验是「被拦当不存在」酿成假修复的第二个现场：WAF 一上线，全库命中都变「已消失」。"""

    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="vc-waf-verify-")
        self.db = os.path.join(self.tmp, "vuln.db")
        p = os.path.join(self.tmp, "sweep")
        with open(p, "w", encoding="utf-8") as f:
            f.write(VERIFY_ENGINE)
        os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR)
        self.engine = p
        self.store = Store(self.db)
        self.store.add_findings([{
            "title": "敏感路径可访问：/.env", "sev": "high", "asset": "127.0.0.1",
            "port": 8080, "endpoint": "/.env", "source": "sweep-paths",
            "evidence": "HTTP 200", "base": "http://127.0.0.1:8080",
        }], "seed.json")
        self.ids = [int(r["id"]) for r in self.store.findings()["rows"]]

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def _verify(self, mode):
        os.environ["WAF_VERIFY_MODE"] = mode
        try:
            v = vfy.Verifier(self.store, engine=self.engine, timeout=60)
            v.start(self.ids)
            for _ in range(600):
                if not v.status()["running"]:
                    break
                time.sleep(0.05)
            return {r["id"]: r for r in self.store.findings(limit=50)["rows"]}[self.ids[0]]
        finally:
            os.environ.pop("WAF_VERIFY_MODE", None)

    def test_blocked_recheck_is_not_gone(self):
        row = self._verify("blocked")
        self.assertEqual(row["verify_state"], "无法判定", row["verify_note"])
        self.assertIn("被 WAF 拦", row["verify_note"])
        self.assertIn("不能判「已消失」", row["verify_note"])
        # 命中本身也带上了「被拦」，列表页能直接看见
        self.assertEqual(row["waf_state"], "blocked")
        self.assertIn("Cloudflare", row["waf"])

    def test_genuinely_gone_is_still_gone(self):
        """对照组：真没了还是要能判「已消失」，别为了防漏报把复验做废。"""
        row = self._verify("gone")
        self.assertEqual(row["verify_state"], "已消失", row["verify_note"])


