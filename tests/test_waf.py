def paths_doc(kind="normal", status=404, alive=None, notes=None, base="http://a.example:80",
              server=""):
    doc = {"base": base,
           "baseline": {"kind": kind, "status": status, "digest": "d", "size": 10,
                        "ctype": "text/html", "final_url": base + "/_probe", "samples": 2},
           "alive": alive or [], "notes": notes or []}
    if server:
        doc["server"] = server
    return doc


class TestClassifyDoc(unittest.TestCase):
    def test_uniform403_baseline_is_blocked(self):
        v = waf.classify_doc(paths_doc(kind="uniform403", status=403))
        self.assertEqual(v["state"], waf.BLOCKED)
        self.assertIn("uniform403", v["reason"])

    def test_normal_404_baseline_is_absent(self):
        v = waf.classify_doc(paths_doc(kind="normal", status=404))
        self.assertEqual(v["state"], waf.ABSENT)

    def test_unknown_baseline_is_unknown(self):
        v = waf.classify_doc({"base": "http://a.example", "baseline": {"kind": "unknown", "samples": 1},
                              "alive": [], "notes": []})
        self.assertEqual(v["state"], waf.UNKNOWN)

    def test_soft404_baseline_is_unknown(self):
        """软 404（全站一个形状）分不清「不存在」和「拦」，只能说不确定。"""
        v = waf.classify_doc(paths_doc(kind="soft404", status=200))
        self.assertEqual(v["state"], waf.UNKNOWN)

    def test_notes_full_of_403_is_blocked_even_without_alive(self):
        """alive=[] 正是漏报发生的地方：notes 里一批 403 必须翻成「被拦」。"""
        doc = paths_doc(kind="normal", status=404,
                        notes=[{"path": "/.git/config", "status": 403,
                                "verdict": "被拒绝（可能受保护/WAF）"}])
        self.assertEqual(waf.classify_doc(doc)["state"], waf.BLOCKED)

    def test_partial_403_with_2xx_is_not_site_blocked(self):
        """有 200 就说明这轮真跑通了：一条 403 不代表全站被拦。"""
        doc = paths_doc(kind="normal", status=404,
                        alive=[{"path": "/.env", "status": 200, "size": 30}],
                        notes=[{"path": "/admin", "status": 403, "verdict": "被拒绝（可能受保护/WAF）"}])
        v = waf.classify_doc(doc)
        self.assertEqual(v["state"], waf.PRESENT)
        self.assertIn("部分路径受保护", v["reason"])

    def test_engine_waf_names_are_taken(self):
        doc = {"check": "secheaders", "target": "a.example", "data": {"waf": ["Cloudflare"]}}
        v = waf.classify_doc(doc)
        self.assertEqual(v["waf"], "Cloudflare")

    def test_server_field_is_used(self):
        v = waf.classify_doc({"url": "http://a/x", "status": 200, "server": "cloudflare",
                              "evidence": "body 含 status"})
        self.assertEqual(v["waf"], "Cloudflare")
        self.assertEqual(v["state"], waf.PRESENT)

    def test_baseline_conclusion_is_present(self):
        """baseline 三检查的产物没有 status：有 conclusion 就算跑通了，别标成「不确定」。"""
        doc = {"check": "secheaders", "target": "a.example", "url": "https://a.example",
               "conclusion": {"level": "warn", "text": "缺失 2 个安全头"}, "risks": [],
               "data": {"waf": []}}
        self.assertEqual(waf.classify_doc(doc)["state"], waf.PRESENT)

    def test_baseline_error_is_unknown(self):
        doc = {"check": "secheaders", "target": "a.example",
               "conclusion": {"level": "fail", "text": "请求失败"}, "error": "timeout",
               "data": {}}
        self.assertEqual(waf.classify_doc(doc)["state"], waf.UNKNOWN)

    def test_empty_doc_is_unknown_not_absent(self):
        for doc in ({}, [], None, "text"):
            with self.subTest(doc=doc):
                self.assertEqual(waf.classify_doc(doc)["state"], waf.UNKNOWN)

    def test_merge_precedence(self):
        P = waf.classify(status=200, body="ok")
        A = waf.classify(status=404, body="not found")
        B = waf.classify(status=403, body="blocked")
        U = waf.classify(status=500)
        self.assertEqual(waf.merge([A, P])["state"], waf.PRESENT)
        self.assertEqual(waf.merge([A, B])["state"], waf.BLOCKED)
        self.assertEqual(waf.merge([A, U])["state"], waf.UNKNOWN)
        self.assertEqual(waf.merge([A, A])["state"], waf.ABSENT)
        self.assertEqual(waf.merge([])["state"], waf.UNKNOWN)

    def test_classify_tree_scopes_by_host(self):
        with tempfile.TemporaryDirectory() as tmp:
            for host, kind in (("a.example", "uniform403"), ("b.example", "normal")):
                d = os.path.join(tmp, host)
                os.makedirs(d)
                with open(os.path.join(d, "paths.json"), "w", encoding="utf-8") as f:
                    json.dump(paths_doc(kind=kind, status=403 if kind == "uniform403" else 404,
                                        base=f"http://{host}"), f)
            a = waf.classify_tree(tmp, "http://a.example")
            b = waf.classify_tree(tmp, "http://b.example")
            self.assertEqual(a["state"], waf.BLOCKED)
            self.assertEqual(b["state"], waf.ABSENT)
            self.assertEqual(a["docs"], 1)

    def test_classify_tree_does_not_mix_ports(self):
        """同一 IP 不同端口是两个服务：:8897 的「被拦」不许算到 :8898 头上。"""
        with tempfile.TemporaryDirectory() as tmp:
            for port, kind in (("8897", "uniform403"), ("8898", "normal")):
                d = os.path.join(tmp, f"127.0.0.1_{port}")
                os.makedirs(d)
                with open(os.path.join(d, "paths.json"), "w", encoding="utf-8") as f:
                    json.dump(paths_doc(kind=kind, status=403 if kind == "uniform403" else 404,
                                        base=f"http://127.0.0.1:{port}"), f)
            blocked = waf.classify_tree(tmp, "http://127.0.0.1:8897")
            absent = waf.classify_tree(tmp, "http://127.0.0.1:8898")
            self.assertEqual(blocked["state"], waf.BLOCKED)
            self.assertEqual(blocked["docs"], 1)
            self.assertEqual(absent["state"], waf.ABSENT)
            self.assertEqual(absent["docs"], 1)
            self.assertNotIn("被", absent["reason"])

    def test_norm_state_rejects_garbage(self):
        self.assertEqual(waf.norm_state("拦"), waf.BLOCKED)
        self.assertEqual(waf.norm_state("BLOCKED"), waf.BLOCKED)
        with self.assertRaises(ValueError):
            waf.norm_state("大概吧")


