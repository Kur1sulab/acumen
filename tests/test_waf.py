class TestIdentify(unittest.TestCase):
    """九家 WAF 的指纹：每条只给一种证据，确认单独一条也能认出来。"""

    CASES = [
        ("Cloudflare", {"CF-RAY": "8a1b-SJC"}, "", ""),
        ("阿里云盾", {"EagleId": "abc"}, "", ""),
        ("阿里云盾", {"Set-Cookie": "acw_tc=0a1b2c; Path=/"}, "", ""),
        ("腾讯云 WAF", {"X-WAF-UUID": "t-1"}, "", ""),
        ("长亭雷池", {}, "", "SafeLine WAF"),
        ("安全狗", {"Set-Cookie": "safedog-flow-item=1=1; Path=/"}, "", ""),
        ("创宇盾", {}, "", "您的请求被创宇盾拦截"),
        ("ModSecurity", {"Server": "Apache/2.4 (Mod_Security)"}, "", ""),
        ("AWS WAF", {"x-amzn-waf-action": "BLOCK"}, "", ""),
        ("F5 BIG-IP", {"X-WA-Info": "-200000000"}, "", ""),
        ("F5 BIG-IP", {}, "", "The requested URL was rejected. Please consult with your administrator."),
    ]

    def test_each_vendor_is_recognized(self):
        for vendor, headers, cookies, body in self.CASES:
            with self.subTest(vendor=vendor):
                names = [x["vendor"] for x in waf.identify(headers, body, cookies)]
                self.assertIn(vendor, names)

    def test_header_names_are_case_insensitive(self):
        # 真服务器头名大小写随缘：CF-Ray / cf-ray / Cf-Ray 必须都认
        for key in ("CF-RAY", "cf-ray", "Cf-Ray"):
            with self.subTest(key=key):
                self.assertEqual(waf.identify({key: "x"})[0]["vendor"], "Cloudflare")

    def test_presence_is_not_blocking(self):
        """有 WAF ≠ 被拦：这是整个模块最重要的一条纪律。"""
        v = waf.classify(status=200, headers={"cf-ray": "x", "Server": "cloudflare"},
                         body="<html>业务页面</html>")
        self.assertEqual(v["state"], waf.PRESENT)
        self.assertEqual(v["waf"], "Cloudflare")

    def test_unknown_vendor_still_judged_blocked(self):
        """自研 WAF 认不出厂商，但 403 仍然是「被拦」，不能滑成「不存在」。"""
        v = waf.classify(status=403, body="<html>Forbidden</html>")
        self.assertEqual(v["state"], waf.BLOCKED)
        self.assertEqual(v["waf"], "")


