def seed(db, specs):
    """specs: [(title, waf_state, waf_name)]；waf_state 为空 = 没判过。"""
    s = Store(db)
    s.add_findings([{
        "title": t, "sev": "high", "asset": "127.0.0.1", "port": 8080,
        "endpoint": "/.env", "source": "sweep-paths", "evidence": "HTTP 200",
        "base": "http://127.0.0.1:8080", "waf_state": st, "waf": nm,
    } for t, st, nm in specs], "seed.json")
    return s


class TestStoreWiring(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.mkdtemp(prefix="vc-waf-")
        self.db = os.path.join(self.tmp, "vuln.db")

    def tearDown(self):
        shutil.rmtree(self.tmp, ignore_errors=True)

    def test_persist_and_filter(self):
        s = seed(self.db, [("被拦的路径", waf.BLOCKED, "Cloudflare"),
                           ("真不存在", waf.ABSENT, ""),
                           ("没判过", "", "")])
        self.assertEqual(s.findings(waf="blocked")["total"], 1)
        self.assertEqual(s.findings(waf="absent")["total"], 1)
        self.assertEqual(s.findings(waf="present")["total"], 0)
        row = s.findings(waf="blocked")["rows"][0]
        self.assertEqual(row["waf"], "Cloudflare")
        self.assertEqual(row["waf_state"], "blocked")

    def test_summary_has_by_waf(self):
        s = seed(self.db, [("被拦的路径", waf.BLOCKED, "Cloudflare"),
                           ("也拦", waf.BLOCKED, "安全狗"),
                           ("真不存在", waf.ABSENT, "")])
        by = {r["waf_state"]: r["n"] for r in s.summary()["by_waf"]}
        self.assertEqual(by.get("blocked"), 2)
        self.assertEqual(by.get("absent"), 1)

    def test_merge_keeps_worst_state(self):
        """同一命中先判「不存在」再判「被拦」：库里的结论必须是「被拦」。"""
        s = seed(self.db, [("同一命中", waf.ABSENT, "")])
        s.add_findings([{"title": "同一命中", "sev": "high", "asset": "127.0.0.1",
                         "port": 8080, "endpoint": "/.env", "source": "sweep-paths",
                         "waf_state": waf.BLOCKED, "waf": "Cloudflare"}], "seed2.json")
        row = s.findings()["rows"][0]
        self.assertEqual(row["waf_state"], "blocked")
        self.assertEqual(row["waf"], "Cloudflare")

    def test_bad_state_rejected(self):
        s = Store(self.db)
        with self.assertRaises(ValueError):
            s.findings(waf="whatever")

    def test_set_waf(self):
        s = seed(self.db, [("命中", "", "")])
        rid = s.findings()["rows"][0]["id"]
        self.assertEqual(s.set_waf([rid], waf.BLOCKED, "SafeLine"), 1)
        self.assertEqual(s.findings(waf="blocked")["rows"][0]["id"], rid)

    def test_csv_carries_three_state(self):
        s = seed(self.db, [("被拦的路径", waf.BLOCKED, "Cloudflare")])
        text = s.export_csv()
        self.assertIn("WAF 三态", text)
        self.assertIn("被 WAF 拦", text)


def run_cli(*argv):
    out, err = io.StringIO(), io.StringIO()
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        code = cli.main(list(argv))
    return code, out.getvalue(), err.getvalue()


