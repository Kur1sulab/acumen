# ---------------------------------------------------------------- 本地靶场

class _Handler(BaseHTTPRequestHandler):
    """一个只回放固定响应的靶机：每条路由模拟一种「目标到底怎么了」。"""

    protocol_version = "HTTP/1.1"

    def log_message(self, format, *args):      # 测试输出保持干净
        pass

    def _send(self, status, body, headers=None):
        raw = body.encode("utf-8")
        self.send_response(status)
        for k, v in (headers or {}).items():
            self.send_header(k, v)
        self.send_header("Content-Type", "text/html; charset=utf-8")
        self.send_header("Content-Length", str(len(raw)))
        self.end_headers()
        self.wfile.write(raw)

    def do_GET(self):
        path = self.path.split("?")[0]
        if path == "/plain404":
            self._send(404, "<html><h1>404 Not Found</h1></html>")
        elif path == "/cloudflare403":
            self._send(403, "<html><title>Attention Required! | Cloudflare</title>"
                            "<body>Ray ID: 8a1b2c3d</body></html>",
                       {"CF-RAY": "8a1b2c3d-SJC", "Server": "cloudflare"})
        elif path == "/safedog404":
            # 国产 WAF 常见的「404 伪装拦截页」：状态码说没有，正文说被拦
            self._send(404, "<html><body>安全狗提示：您的请求被拦截</body></html>",
                       {"Set-Cookie": "safedog-flow-item=1=1"})
        elif path == "/challenge":
            self._send(200, "<html><title>Just a moment...</title>"
                            "<body>Checking your browser before accessing</body></html>",
                       {"Server": "cloudflare"})
        elif path == "/err502":
            self._send(502, "<html><h1>502 Bad Gateway</h1></html>")
        elif path == "/modsec406":
            self._send(406, "<html><body>Not Acceptable! This error was generated by "
                            "Mod_Security.</body></html>")
        else:
            self._send(200, "<html><body>hello</body></html>")


def fetch(url):
    """真发一次 GET，拿回 (status, headers_dict, body) —— 4xx/5xx 也要拿到响应体。"""
    try:
        with urllib.request.urlopen(url, timeout=5) as r:
            return r.status, dict(r.headers.items()), r.read(65536).decode("utf-8", "replace")
    except urllib.error.HTTPError as e:
        return e.code, dict(e.headers.items()), e.read(65536).decode("utf-8", "replace")


